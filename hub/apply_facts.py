def norm(s):
    return ''.join(s.split())

def apply(kind, mapping):
    changed = 0
    for eid, newfacts in mapping.items():
        path = os.path.join(ROOT, 'data', 'entities', kind, f'{eid}.yaml')
        if not os.path.exists(path):
            print(f'  !! 缺失 {path}')
            continue
        d = yaml.safe_load(open(path, encoding='utf-8'))
        vf = d.get('verified_facts', [])
        existing_prefixes = {norm(v.get('fact',''))[:25] for v in vf}
        added = 0
        for fact, source in newfacts:
            if norm(fact)[:25] in existing_prefixes:
                continue
            vf.append({'fact': fact, 'source': source})
            existing_prefixes.add(norm(fact)[:25])
            added += 1
        if added:
            d['verified_facts'] = vf
            with open(path, 'w', encoding='utf-8') as f:
                yaml.dump(d, f, allow_unicode=True, sort_keys=False, default_flow_style=False, width=200)
            changed += 1
        print(f'  {eid}: +{added} fact(s)')
    print(f'{kind}: {changed} 文件更新')

